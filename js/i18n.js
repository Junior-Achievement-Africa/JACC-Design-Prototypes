JACC.lang = () => JACC._lang;

JACC.t = (key, vars = {}) => {
  const dict = I18N[JACC._lang] || I18N.en;
  let str = dict[key] ?? I18N.en[key] ?? key;
  Object.keys(vars).forEach((k) => {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
  });
  return str;
};

JACC.setLang = (id) => {
  if (!JACC.LANGS.some((l) => l.id === id)) id = 'en';
  JACC._lang = id;
  localStorage.setItem('jacc-lang', id);
  document.documentElement.setAttribute('lang', id);
  window.dispatchEvent(new CustomEvent('jacc:lang', { detail: { lang: id } }));
};

document.documentElement.setAttribute('lang', JACC._lang);
